// api/_utils/researchDirectory.test.js
//
// Research universe Build 1: the generated directory's contents (build prompt section 4). The file is generated
// by scripts/build-research-directory.mjs and never edited by hand; these rows hold whatever a monthly re-run
// writes to the same contract.

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { RESEARCH_DIRECTORY, RESEARCH_DIRECTORY_META } from './researchDirectory.js';
import { ALL_TICKERS, INDUSTRY_ETFS, SECTOR_ETFS, STOCK_UNIVERSE } from './rankingConfig.js';
import { INDEX_SYMBOLS as INDEX_REGISTRY_SYMBOLS } from './indexRegistry.js';
import { INDEX_SYMBOLS as INTRADAY_INDEX_SYMBOLS } from './intraday/universe.js';
import { INDEX_NAMES } from './sharedResearch/stepSchema.js';
import { INDEX_SUBJECTS } from './wireContracts.js';
import { PRACTICE_FIELD_FUNDS } from '../../src/data/practiceFieldFunds.js';
import { INDEX_SYMBOLS as CLIENT_INDEX_SYMBOLS } from '../../src/constants/indexRegistry.js';

const SRC = readFileSync(fileURLToPath(new URL('./researchDirectory.js', import.meta.url)), 'utf8').replace(/\r\n/g, '\n');
const SECTOR_IDS = Object.keys(STOCK_UNIVERSE);
const SYMBOLS = Object.keys(RESEARCH_DIRECTORY);
// The symbol shape resolveSymbol (sharedResearch/companies.js) accepts, so a later build can resolve every entry.
const SYMBOL = /^[A-Z0-9][A-Z0-9-]{0,11}$/;
// Control, zero-width and bidi characters and the byte-order mark, by code point.
const INVISIBLE_RANGES = [[0x00, 0x1f], [0x7f, 0x9f], [0x200b, 0x200f], [0x202a, 0x202e], [0x2060, 0x2064], [0x2066, 0x2069], [0xfeff, 0xfeff]];
const INVISIBLE = { test: (s) => [...s].some((ch) => INVISIBLE_RANGES.some(([lo, hi]) => ch.codePointAt(0) >= lo && ch.codePointAt(0) <= hi)) };
const ENTRY_LINE = /^ {2}("[^"\\]*(?:\\.[^"\\]*)*"): \[(.*)\],$/;
const entryLines = SRC.split('\n').filter((l) => l.startsWith('  "'));

const displayString = (v) => typeof v === 'string' && v.length > 0 && v === v.trim() && !/\s{2}/.test(v) && !INVISIBLE.test(v);

describe('every entry', () => {
  it('has a well-formed symbol, a name, one of the 11 sector ids and an industry or null', () => {
    expect(SYMBOLS.length).toBeGreaterThan(0);
    for (const s of SYMBOLS) {
      const e = RESEARCH_DIRECTORY[s];
      expect(s).toMatch(SYMBOL);
      expect(Array.isArray(e) && e.length === 3).toBe(true);
      expect(displayString(e[0])).toBe(true);
      expect(SECTOR_IDS).toContain(e[1]);
      expect(e[2] === null || displayString(e[2])).toBe(true);
    }
  });
  it('is frozen, as is the directory', () => {
    expect(Object.isFrozen(RESEARCH_DIRECTORY)).toBe(true);
    expect(Object.isFrozen(RESEARCH_DIRECTORY_META)).toBe(true);
    for (const s of SYMBOLS) expect(Object.isFrozen(RESEARCH_DIRECTORY[s])).toBe(true);
  });
});

describe('no duplicate, one entry per line, sorted by symbol', () => {
  const lineSymbols = entryLines.map((l) => {
    const m = ENTRY_LINE.exec(l);
    return m ? JSON.parse(m[1]) : `UNPARSED: ${l}`;
  });
  it('every entry line parses, and the lines are the entries (a repeated key in the source would collapse silently)', () => {
    expect(lineSymbols.filter((s) => s.startsWith('UNPARSED'))).toEqual([]);
    expect(lineSymbols.length).toBe(SYMBOLS.length);
    expect(new Set(lineSymbols).size).toBe(lineSymbols.length);
  });
  it('lines run in code-point order of symbol', () => {
    const sorted = [...lineSymbols].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
    expect(lineSymbols).toEqual(sorted);
  });
  it('each line holds exactly name, sector and industry (no market value)', () => {
    for (const l of entryLines) {
      const parsed = JSON.parse(`[${ENTRY_LINE.exec(l)[2]}]`);
      expect(parsed.length).toBe(3);
    }
    expect(SRC).not.toMatch(/market_capitalization|marketValue/);
  });
});

describe('no symbol from the game list or a fund or index list', () => {
  const lists = {
    'ALL_TICKERS (the 228)': ALL_TICKERS,
    SECTOR_ETFS,
    'INDUSTRY_ETFS (industry funds)': Object.values(INDUSTRY_ETFS).flat(),
    'index symbols (api indexRegistry)': [...INDEX_REGISTRY_SYMBOLS],
    'index symbols (src indexRegistry)': [...CLIENT_INDEX_SYMBOLS],
    'index symbols (intraday universe)': INTRADAY_INDEX_SYMBOLS,
    'index names (Work an idea)': INDEX_NAMES,
    'index subjects (Wire)': INDEX_SUBJECTS,
    'Practice Field funds': Object.keys(PRACTICE_FIELD_FUNDS),
  };
  it.each(Object.entries(lists))('%s', (_name, list) => {
    expect(list.length).toBeGreaterThan(0);
    expect(list.filter((s) => Object.hasOwn(RESEARCH_DIRECTORY, s))).toEqual([]);
  });
});

describe('the header', () => {
  it('states that it is generated, the date, the count and the floor, and they match the data', () => {
    expect(SRC).toContain('// GENERATED: generated by scripts/build-research-directory.mjs; do not edit by hand.');
    expect(SRC).toContain(`// Generated: ${RESEARCH_DIRECTORY_META.generatedOn}`);
    expect(RESEARCH_DIRECTORY_META.generatedOn).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    const count = /^\/\/ Count: ([\d,]+)$/m.exec(SRC);
    expect(Number(count[1].replace(/,/g, ''))).toBe(SYMBOLS.length);
    expect(RESEARCH_DIRECTORY_META.count).toBe(SYMBOLS.length);
    expect(RESEARCH_DIRECTORY_META.floorUsd).toBe(1_000_000_000);
    expect(SRC).toContain('// Floor: market value at or above $1,000,000,000');
  });
  it('states the per-sector counts the data holds', () => {
    const line = /^\/\/ Per sector: (.*)$/m.exec(SRC)[1];
    const stated = Object.fromEntries(line.split(', ').map((p) => p.split(' ')).map(([id, n]) => [id, Number(n)]));
    const actual = Object.fromEntries(SECTOR_IDS.map((id) => [id, SYMBOLS.filter((s) => RESEARCH_DIRECTORY[s][1] === id).length]));
    expect(stated).toEqual(actual);
  });
  it('is between 1,000 and 5,000 entries (the generator\'s own stop)', () => {
    expect(SYMBOLS.length).toBeGreaterThanOrEqual(1000);
    expect(SYMBOLS.length).toBeLessThanOrEqual(5000);
  });
});

describe('a data-only module', () => {
  it('imports nothing, reads nothing and exports only the directory and its meta', () => {
    // Code lines only: a company name may hold any of these words.
    const code = SRC.split('\n').filter((l) => !l.startsWith('  "') && !l.startsWith('//')).join('\n');
    expect(code.split('\n').length).toBeLessThan(20);
    expect(code).not.toMatch(/^\s*import\b|\bimport\s*\(|\brequire\s*\(|process\.|fetch\(|Date\b/m);
    const exports = [...SRC.matchAll(/^export const (\w+)/gm)].map((m) => m[1]);
    expect(exports).toEqual(['RESEARCH_DIRECTORY_META', 'RESEARCH_DIRECTORY']);
  });
});
